"""API endpoint routers for health, dashboard, patients, assessments, and model card."""

from datetime import datetime, timezone
import uuid
from fastapi import APIRouter, HTTPException, Query, status
from app.core.config import settings
from app.ml.pipeline import ModelService
from app.schemas.assessment import AssessmentRequest, AssessmentResponse
from app.schemas.model_card import ModelCardResponse
from app.schemas.patient import (
    DashboardSummary,
    PatientRecord,
    PatientSummary,
)
from app.services.patient_service import PatientService

api_router = APIRouter()


@api_router.get(
    "/health",
    summary="Health check",
    tags=["System"],
)
async def health_check() -> dict[str, str | bool]:
    """Returns application status, version, and model initialization state."""
    model_service = ModelService.get_instance()
    return {
        "status": "healthy",
        "app_name": settings.APP_NAME,
        "app_version": settings.APP_VERSION,
        "demonstration_mode": settings.DEMONSTRATION_MODE,
        "synthetic_data_only": settings.SYNTHETIC_DATA_ONLY,
        "model_initialized": model_service.is_initialized,
        "model_version": model_service.model_version,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }


@api_router.get(
    "/v1/dashboard",
    response_model=DashboardSummary,
    summary="Dashboard aggregate statistics",
    tags=["Dashboard"],
)
async def get_dashboard() -> DashboardSummary:
    """Returns aggregated summary metrics calculated from synthetic patient records."""
    return PatientService.get_dashboard_summary()


@api_router.get(
    "/v1/patients",
    response_model=list[PatientSummary],
    summary="List synthetic patients",
    tags=["Patients"],
)
async def list_patients(
    search: str | None = Query(None, description="Search by ID, display code, or care unit"),
    category: str | None = Query(None, description="Filter by demonstration review category"),
    sort_by: str = Query("priority_desc", description="Sort by 'priority_desc', 'priority_asc', 'age_desc', 'id'"),
) -> list[PatientSummary]:
    """Returns synthetic demonstration patient summaries with optional search and filters."""
    return PatientService.list_patients(search=search, category=category, sort_by=sort_by)


@api_router.get(
    "/v1/patients/{patient_id}",
    response_model=PatientRecord,
    summary="Get patient details and observation history",
    tags=["Patients"],
)
async def get_patient_details(patient_id: str) -> PatientRecord:
    """Retrieves single synthetic patient record with observation history.

    Returns 404 if not found.
    """
    patient = PatientService.get_patient(patient_id)
    if not patient:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Patient record '{patient_id}' was not found in the synthetic demonstration store.",
        )
    return patient


@api_router.post(
    "/v1/assessments",
    response_model=AssessmentResponse,
    status_code=status.HTTP_200_OK,
    summary="Run demonstration review-priority assessment",
    tags=["Assessment"],
)
async def create_assessment(payload: AssessmentRequest) -> AssessmentResponse:
    """Evaluates vital signs using the real trained scikit-learn model and

    returns transparent feature contributions and illustrative threshold flags.
    No assessment payload is persisted to disk or database.
    """
    model_service = ModelService.get_instance()

    score, category, contributions, flags, interpretation = model_service.predict(
        age=payload.age,
        heart_rate=payload.heart_rate,
        respiratory_rate=payload.respiratory_rate,
        oxygen_saturation=payload.oxygen_saturation,
        body_temperature=payload.body_temperature,
        systolic_blood_pressure=payload.systolic_blood_pressure,
    )

    safety_disclaimer = (
        "EDUCATIONAL DEMONSTRATION NOTICE: This assessment score is a DEMONSTRATION REVIEW PRIORITY "
        "generated by a synthetic logistic regression classifier. It is NOT a clinical risk estimate, "
        "medical diagnosis, prognosis, or treatment guideline. Do not use for real patient care."
    )

    return AssessmentResponse(
        assessment_id=f"ASSESS-{uuid.uuid4().hex[:10].upper()}",
        demonstration_score=score,
        demonstration_category=category,  # type: ignore[arg-type]
        model_version=model_service.model_version,
        input_summary={
            "age": float(payload.age),
            "heart_rate": payload.heart_rate,
            "respiratory_rate": payload.respiratory_rate,
            "oxygen_saturation": payload.oxygen_saturation,
            "body_temperature": payload.body_temperature,
            "systolic_blood_pressure": payload.systolic_blood_pressure,
        },
        feature_contributions=contributions,
        threshold_flags=flags,
        score_interpretation=interpretation,
        safety_disclaimer=safety_disclaimer,
        timestamp=datetime.now(timezone.utc).isoformat(),
    )


@api_router.get(
    "/v1/model-card",
    response_model=ModelCardResponse,
    summary="Model metadata and holdout evaluation metrics",
    tags=["Model Transparency"],
)
async def get_model_card() -> ModelCardResponse:
    """Returns actual measured evaluation metrics on holdout synthetic data,

    model coefficients, methodology, and limitations.
    """
    model_service = ModelService.get_instance()
    return model_service.get_model_card()
